"""Opt-in SUPERVISED 1D TEM deep-learning inversion. No pre-trained water classifier.

Dataset is a trusted physics/field-labelled NPZ: signals (N, G) positive |dB/dt|,
resistivity (N, D) positive 1D layer targets, times_s (G,) and depths_m (D,).
Synthetic/geological model must be generated by SimPEG or other validated forward
codes and independently checked. Never train on unlabelled real measurements.
"""
from __future__ import annotations
from pathlib import Path
import json
import numpy as np


def _torch():
    try:
        import torch
        from torch import nn
    except ImportError as exc:
        raise RuntimeError('深度学习模块需要 pip install torch') from exc
    return torch,nn


def validate_axes(times, depths):
    """SI axes shared by training data and model metadata inspections."""
    if times.ndim != 1 or depths.ndim != 1 or not len(times) or not len(depths):
        raise ValueError('时间/深度轴必须为非空一维数组')
    if not (np.isfinite(times).all() and np.isfinite(depths).all()):
        raise ValueError('时间/深度轴必须为有限值')
    if np.any(times <= 0) or np.any(depths < 0):
        raise ValueError('时间必须大于零（秒），深度不得小于零（米）')
    if not (np.all(np.diff(times) > 0) and np.all(np.diff(depths) > 0)):
        raise ValueError('时间门/深度轴必须严格递增')


def load_pairs(path):
    with np.load(path,allow_pickle=False) as ds:
        needed={'signals','resistivity','times_s','depths_m'}
        if not needed.issubset(ds.files):
            raise ValueError('NPZ缺少: '+str(needed-set(ds.files)))
        signal=np.asarray(ds['signals'],dtype='float32')
        rho=np.asarray(ds['resistivity'],dtype='float32')
        times=np.asarray(ds['times_s'],dtype=float)
        depths=np.asarray(ds['depths_m'],dtype=float)
    if signal.ndim!=2 or rho.ndim!=2 or signal.shape[0]!=rho.shape[0]:
        raise ValueError('signals/resistivity必须是样本数一致的二维数组')
    if len(signal)<12 or signal.shape[1]<8 or rho.shape[1]<4:
        raise ValueError('至少12组标注数据，每组8个时间门、4个深度层')
    if times.shape!=(signal.shape[1],) or depths.shape!=(rho.shape[1],):
        raise ValueError('时间/深度轴长度与矩阵不符')
    validate_axes(times, depths)
    if not(np.all(np.isfinite(signal)) and np.all(np.isfinite(rho)) and
           np.all(signal>0) and np.all(rho>0)):
        raise ValueError('训练对必须是正数有限值，不能直接使用无标注曲线')
    return signal,rho,times,depths


def make_network(n_times,n_depth):
    """Compact residual 1D convolution encoder with dense depth decoder."""
    torch,nn=_torch()
    class Net(nn.Module):
        def __init__(self):
            super().__init__()
            self.encoder=nn.Sequential(
                nn.Conv1d(1,32,5,padding=2),nn.GELU(),
                nn.Conv1d(32,32,3,padding=1),nn.GELU(),
                nn.Conv1d(32,64,3,stride=2,padding=1),nn.GELU(),
                nn.Conv1d(64,64,3,padding=1),nn.GELU(),
                nn.AdaptiveAvgPool1d(8))
            self.decoder=nn.Sequential(nn.Flatten(),nn.Linear(64*8,128),nn.GELU(),
                                       nn.Dropout(.12),nn.Linear(128,n_depth))
        def forward(self,x):
            return self.decoder(self.encoder(x[:,None,:]))
    return Net()


def train(npz_path,out_prefix,epochs=60,lr=1e-3,seed=2026,callback=None):
    torch,_=_torch()
    torch.manual_seed(seed)
    x,y,times,depths=load_pairs(npz_path)
    # Mean and scale computed from TRAIN ONLY, saved with model.
    rng=np.random.default_rng(seed)
    ix=rng.permutation(len(x)); ntrain=max(1,int(.8*len(ix)))
    tr,va=ix[:ntrain],ix[ntrain:]
    logx=np.log10(x);logy=np.log10(y)
    xm=logx[tr].mean(axis=0);xs=logx[tr].std(axis=0)+1e-5
    ym=logy[tr].mean(axis=0);ys=logy[tr].std(axis=0)+1e-5
    X=torch.tensor((logx-xm)/xs,dtype=torch.float32)
    Y=torch.tensor((logy-ym)/ys,dtype=torch.float32)
    model=make_network(len(times),len(depths))
    optim=torch.optim.Adam(model.parameters(),lr=lr)
    best=float('inf');stale=0;history=[]
    for epoch in range(int(epochs)):
        model.train()
        for batch in np.array_split(tr,max(1,int(np.ceil(len(tr)/32)))):
            optim.zero_grad()
            pred=model(X[batch]); loss=torch.mean((pred-Y[batch])**2)
            loss.backward();optim.step()
        model.eval()
        with torch.no_grad():
            tr_loss=float(torch.mean((model(X[tr])-Y[tr])**2))
            va_loss=float(torch.mean((model(X[va])-Y[va])**2))
        history.append((epoch+1,tr_loss,va_loss))
        if callback:callback(epoch+1,int(epochs),tr_loss,va_loss)
        if va_loss<best-1e-5:
            best=va_loss;stale=0
            bestweights={k:v.detach().cpu().clone() for k,v in model.state_dict().items()}
        else:
            stale+=1
        if stale>=10:break
    model.load_state_dict(bestweights)
    pref=Path(out_prefix);pref.parent.mkdir(parents=True,exist_ok=True)
    torch.save({'state_dict':model.state_dict(),'n_times':len(times),'n_depths':len(depths)},str(pref)+'.pt')
    np.savez_compressed(str(pref)+'_metadata.npz',times_s=times,depths_m=depths,xmean=xm,xstd=xs,ymean=ym,ystd=ys)
    (Path(str(pref)+'_history.csv')).write_text('epoch,train_mse,val_mse\n'+
                                    ''.join(f'{a},{b},{c}\n' for a,b,c in history),encoding='utf-8')
    return {'best_validation_mse':best,'epochs':len(history),'model_prefix':str(pref)}


def predict(prefix,signal,time_axis):
    """Inference only for axes exactly matching training. Load ONLY trusted .pt files."""
    torch,_=_torch()
    prefix=str(prefix)
    with np.load(prefix+'_metadata.npz',allow_pickle=False) as meta:
        t=meta['times_s'];depths=meta['depths_m']
        xm=meta['xmean'];xs=meta['xstd'];ym=meta['ymean'];ys=meta['ystd']
    if not(np.shape(signal)==np.shape(t) and np.allclose(time_axis,t,rtol=1e-6,atol=0)):
        raise ValueError('实测门序列与训练时间轴不一致；请先重新采样并核对设备')
    if not np.all(np.isfinite(signal)) or np.any(np.asarray(signal)<=0):
        raise ValueError('待预测响应无效')
    # weights_only=True prevents untrusted pickle objects in newer PyTorch.
    checkpoint=torch.load(prefix+'.pt',map_location='cpu',weights_only=True)
    model=make_network(len(t),len(depths))
    model.load_state_dict(checkpoint['state_dict']);model.eval()
    feat=torch.tensor(((np.log10(signal)-xm)/xs)[None,:],dtype=torch.float32)
    with torch.no_grad(): output=model(feat)[0].numpy()
    with np.errstate(over='ignore', under='ignore', invalid='ignore'):
        rho = 10**(output*ys+ym)
    if not np.isfinite(rho).all() or np.any(rho <= 0):
        raise ValueError('模型预测产生非有限或非正电阻率；输入可能偏离训练分布，请核对数据并重新训练')
    return depths,rho


def predict_line(df,model_prefix,settings=None,line_id=None):
    """Apply a trusted trained 1D resistivity predictor to a matched TEM line.

    Reuses model/time gate validation; creates vertically stacked 1D predictions,
    never labels a conductor as confirmed water, and does not infer 3D structure.
    """
    from .model import Settings
    from .processing import process,pick_anomalies
    cfg=settings or Settings()
    result=process(df,cfg,line_id)
    with np.load(str(model_prefix)+'_metadata.npz',allow_pickle=False) as d:
        ref_times=d['times_s'].copy();depths=d['depths_m'].copy()
    xs=[];rhos=[];ids=[]
    for st,g in result.readings.groupby('station',sort=False):
        g=g.sort_values('time_s')
        times=g['time_s'].to_numpy()
        if len(times)!=len(ref_times) or not np.allclose(times,ref_times,atol=0,rtol=1e-6):
            raise ValueError(f'测点 {st} 的时间门与训练时不一致：不能插值猜测后直接预测')
        if not np.all(g['accepted'].to_numpy()):
            raise ValueError(f'测点 {st} 存在低信噪比/干扰门；请核对并使用与训练一致的质控策略')
        amp=np.abs(g['dbdt_clean_t_s'].to_numpy())
        zz,rho=predict(model_prefix,amp,times)
        xs.append(float(g['x_m'].iloc[0]));ids.append(str(st));rhos.append(rho)
    order=np.argsort(xs)
    sortedx=np.array(xs)[order]
    if np.any(np.diff(sortedx)<=0):
        raise ValueError('测点 x_m 必须单调不重复')
    matrix=np.array(rhos)[order].T
    result.profile={'x_m':sortedx,'depth_m':depths,'rho_ohm_m':matrix,
                    'stations':[ids[i] for i in order],
                    'view_type':'SUPERVISED 1D-CNN predictions stitched into section, NOT physics inversion'}
    anomalies,mask=pick_anomalies(result.profile,cfg)
    result.profile['candidate_mask']=mask
    result.anomalies=anomalies
    result.quality['engine']='user-trained supervised 1D-CNN, no externally validated mine-water classifier'
    result.quality['limitations'] += ['神经网络输出仅基于用户提供标注集学习，无法替代 TEM 物理正反演和现场钻探验证']
    return result
